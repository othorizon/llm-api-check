const CACHE = Object.fromEntries(Object.entries(G).map(([k, v]) => [k, v.split(',')]))

export function textWidth(text, scale, tracking = 1) {
  return text.length * (5 + tracking) * scale - tracking * scale
}

/** 以圆角像素块绘制文本 */
export function drawText(canvas, text, x, y, scale, color, alpha = 1, tracking = 1) {
  let cx = x
  for (const ch of text.toUpperCase()) {
    const rows = CACHE[ch] ?? CACHE[' ']
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (rows[r][c] === '1') {
          canvas.rect(Math.round(cx + c * scale), Math.round(y + r * scale), Math.ceil(scale), Math.ceil(scale), color, alpha)
        }
      }
    }
    cx += (5 + tracking) * scale
  }
  return cx - tracking * scale
}
